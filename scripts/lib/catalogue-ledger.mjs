/**
 * Every catalogue's facts, each path under its owner: the shared worlds (the solar system and
 * its reach, the Galaxy and the nearest stars, named stars and black holes, the cosmic map, the
 * Sun), then each simulation's own.
 */
const catalogueFacts = () => [
  ...solarCatalogueFacts().map((entry) => ({ ...entry, path: `solar-system/${entry.path}` })),
  ...probeCatalogueFacts().map((entry) => ({ ...entry, path: `solar-system/${entry.path}` })),
  ...galaxyCatalogueFacts().map((entry) => ({ ...entry, path: `galaxy/${entry.path}` })),
  ...stellarCatalogueFacts().map((entry) => ({ ...entry, path: `stellar/${entry.path}` })),
  ...cosmosCatalogueFacts().map((entry) => ({ ...entry, path: `cosmos/${entry.path}` })),
  ...sunFacts().map((entry) => ({ ...entry, path: `sun/${entry.path}` })),
  ...orreryFacts().map((entry) => ({ ...entry, path: `orrery/${entry.path}` })),
  ...giantsFacts().map((entry) => ({ ...entry, path: `giants/${entry.path}` })),
  ...blackHoleFacts().map((entry) => ({ ...entry, path: `black-hole/${entry.path}` })),
];

const START = "<!-- catalogue:start -->";
const END = "<!-- catalogue:end -->";
export const LEDGER = new URL("../../docs/science-sources.md", import.meta.url);

const symbol = (unit) => (unit in UNITS ? UNITS[unit].symbol : unit === "percent" ? "%" : "");
/** As written, up to four significant figures: 6.5 × 10⁹, 9.785. */
const significant = (v) =>
  Math.abs(v).toExponential().split("e")[0].replace(".", "").replace(/0+$/, "").length || 1;
const number = (value) => formatSignificant(value, "en", Math.min(4, significant(value)));
const cell = (text) => String(text).replaceAll("|", "\\|");

function valueOf(fact) {
  const unit = symbol(fact.unit);
  const span = fact.range ? `${number(fact.range[0])}–${number(fact.range[1])}` : "";
  const value =
    fact.value === undefined ? span : span ? `${number(fact.value)} (${span})` : number(fact.value);
  return `${value}${unit ? ` ${unit}` : ""}`;
}

/** Every engine: the shared catalogue's, then the planets' that only Giants describes. */
const engines = () => [
  ...Object.entries(ENGINES).map(([id, engine]) => ({ path: `stellar/engines.${id}`, engine })),
  ...Object.entries(RUNG_ENGINES)
    .filter(([, engine]) => !Object.values(ENGINES).includes(engine))
    .map(([id, engine]) => ({ path: `giants/engines.${id}`, engine })),
];

/** The generated block: every card figure and engine, then the sources they cite. */
function block() {
  const used = new Set();
  const rows = catalogueFacts().map(({ path, fact }) => {
    const citations = factSources(fact);
    citations.forEach((source) => used.add(source));
    const note = [fact.show ? `shown in ${symbol(fact.show)}` : "", fact.note ?? ""]
      .filter(Boolean)
      .join("; ");
    return `| \`${path}\` | ${cell(valueOf(fact))} | ${citations.map((source) => `\`${source}\``).join(", ")} | ${fact.status === "flag" ? "**flag**" : fact.status} | ${cell(note)} |`;
  });
  const engineRows = engines().map(({ path, engine }) => {
    engine.sources.forEach((source) => used.add(source));
    const process = engine.debated ? `${engine.process} or ${engine.debated}` : engine.process;
    return `| \`${path}\` | ${process} | ${engine.sources.map((source) => `\`${source}\``).join(", ")} | ${engine.status === "flag" ? "**flag**" : engine.status} | ${cell(engine.note)} |`;
  });
  const sources = Object.entries(SOURCES)
    .filter(([id]) => used.has(id))
    .map(([id, s]) => `| \`${id}\` | ${cell(s.link ? `[${s.cite}](${s.link})` : s.cite)} |`);
  return [
    START,
    "<!-- Generated by npm run docs:catalogue from the solar system, galaxy, cosmos, sun, orrery, giants and black-hole catalogues; edit those files instead. -->",
    "",
    "| Fact | Value | Source | Status | Note |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "| Engine | Process | Source | Status | Note |",
    "| --- | --- | --- | --- | --- |",
    ...engineRows,
    "",
    "| Source | Citation |",
    "| --- | --- |",
    ...sources,
    "",
    END,
  ].join("\n");
}

/** The ledger with its catalogue block regenerated and formatted like the rest of the repo. */
export async function ledger() {
  const text = readFileSync(LEDGER, "utf8");
  const at = text.indexOf(START);
  const end = text.indexOf(END);
  if (at < 0 || end < at) throw new Error(`docs/science-sources.md lacks ${START} … ${END}`);
  const next = text.slice(0, at) + block() + text.slice(end + END.length);
  const formatted = await format("science-sources.md", next, { printWidth: 100 });
  if (formatted.errors.length) throw new Error("Could not format the science ledger.");
  return { current: text, next: formatted.code };
}
