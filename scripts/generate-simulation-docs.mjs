import { readFileSync } from "node:fs";

import { format } from "oxfmt";

import { BLACK_HOLE_EQUATIONS } from "../src/features/black-hole/lib/equations.ts";
import { PRESETS } from "../src/features/black-hole/lib/holes/index.ts";
import { BLACK_HOLE_COPY } from "../src/features/black-hole/lib/parameters.ts";
import { pathForHole } from "../src/features/black-hole/routing.ts";
import specification from "../src/features/black-hole/technical.ts";
import { syncGenerated } from "./lib/generated.mjs";

/** The app passes the same values as ICU arguments; English formatting here. */
const withValues = (text) =>
  text.replace(/\{(\w+)\}/g, (match, name) =>
    name in BLACK_HOLE_COPY ? BLACK_HOLE_COPY[name].toLocaleString("en") : match,
  );

const root = new URL("../", import.meta.url);
const feature = "src/features/black-hole/";
const copy = JSON.parse(
  readFileSync(new URL(`${feature}messages/en.json`, root), "utf8"),
).technicalDetails;
const lines = [
  "<!-- Generated by npm run docs:generate. Edit technical.ts and messages/* instead. -->",
  "# Black-hole observatory",
  "",
  copy.summary,
  "",
  "The in-app Technical details button uses the same structured specification and localized copy.",
  "All preset subpages below share this implementation; they are configurations, not separate solvers.",
  "",
  "## Preset subpages",
  "",
  "Routes carry no language prefix. Mass and spin below are initial preset values, not observational uncertainty estimates.",
  "",
  "| Preset | Route | Mass (solar masses) | Spin | Sky | Jet strength |",
  "| --- | --- | --- | --- | --- | --- |",
  ...PRESETS.map(
    (p) =>
      `| ${p.name} | \`${pathForHole(p.id)}\` | ${p.massSolar} | ${p.spin} | ${p.sky} | ${p.jet} |`,
  ),
  "",
  `## ${copy.featuresTitle}`,
  "",
  ...specification.features.map((id) => `- ${copy.features[id]}`),
  "",
];
lines.push(
  `## ${copy.references}`,
  "",
  ...specification.references.map((ref) => `- [${ref.title}](${ref.url})`),
  "",
  "See [physics audit](../../../docs/black-hole-physics-audit.md) for verification scope and remaining limits.",
  "",
);
for (const section of specification.sections) {
  lines.push(
    `## ${copy.sections[section.id].title}`,
    "",
    withValues(copy.sections[section.id].body),
    "",
  );
  // Plain formulas print as text; library equations print their LaTeX for GitHub's math blocks.
  const text = section.equations.filter((entry) => typeof entry === "string");
  if (text.length) lines.push("```text", ...text, "```", "");
  for (const entry of section.equations) {
    if (typeof entry === "string") continue;
    const equation = BLACK_HOLE_EQUATIONS[entry.equation];
    if (!equation) throw new Error(`Unknown equation "${entry.equation}"`);
    lines.push("```math", equation.toLatex(), "```", "");
  }
}
lines.push(
  "## Maintenance",
  "",
  "`technical.ts` owns section IDs, equations, and scientific references. The `technicalDetails` namespace in `messages/en.json` and `messages/cs.json` owns translated prose. Review the implementation when changing these notes; some older lesson captions describe idealized theory rather than the renderer. Regenerate this README with `npm run docs:generate` and check it with `npm run docs:check`.",
  "",
);
const formatted = await format("README.md", lines.join("\n"), { printWidth: 100 });
if (formatted.errors.length) throw new Error("Could not format simulation README.");
syncGenerated({
  file: new URL(`${feature}README.md`, root),
  content: formatted.code,
  command: "npm run docs:generate",
});
