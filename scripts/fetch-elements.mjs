/**
 * Fetches the periodic table from IUPAC's Commission on Isotopic Abundances and Atomic Weights
 * and rewrites the generated part of packages/toolkit/src/science/elements.ts: every element's
 * atomic number, symbol, English name and abridged standard atomic weight, or, for an element
 * without one, the mass number of its longest-lived isotope. Run by hand when CIAAW revises its
 * tables, then `npm run format`:
 *
 *   node scripts/fetch-elements.mjs          # rewrite
 *   node scripts/fetch-elements.mjs --check  # fail if the file is out of date
 *
 * Sources: CIAAW's abridged standard atomic weights (five significant figures; Atomic Weights
 * 2021 with the 2024 revisions) and its list of the most stable isotopes of radioactive elements
 * (NUBASE2020). Where that list gives several isotopes, the one with the longest recommended
 * half-life is taken. Every value is cross-checked against NIST's Atomic Weights and Isotopic
 * Compositions: the same symbol for each Z, and each abridged weight within the combined
 * uncertainties of NIST's standard atomic weight.
 */
import { readFile } from "node:fs/promises";

import { syncGenerated } from "./lib/generated.mjs";
import { fetchText } from "./lib/net.mjs";

const OUT = new URL("../packages/toolkit/src/science/elements.ts", import.meta.url);
const ABRIDGED = "https://www.ciaaw.org/abridged-atomic-weights.htm";
const RADIOACTIVE = "https://www.ciaaw.org/radioactive-elements.htm";
const NIST =
  "https://physics.nist.gov/cgi-bin/Compositions/stand_alone.pl?ele=&ascii=ascii2&isotype=some";
const BEGIN = "/* <generated by scripts/fetch-elements.mjs: do not edit by hand> */";
const END = "/* </generated> */";

const SECONDS = { ms: 1e-3, s: 1, min: 60, h: 3600, d: 86400, a: 31556926, ka: 31556926e3 };
SECONDS.Ma = SECONDS.ka * 1e3;

const decode = (html) =>
  html
    .replace(/<[^>]*>/g, "")
    .replaceAll("&nbsp;", " ")
    .replaceAll("&plusmn;", "±")
    .replaceAll("&mdash;", "—")
    .trim();

/** Table rows as arrays of decoded cell texts. */
const rows = (html) =>
  [...html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)]
    .map(([, row]) => [...row.matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map(([, td]) => decode(td)))
    .filter((cells) => cells.length > 0);

function parseAbridged(html) {
  const elements = rows(html)
    .filter((cells) => cells.length === 5 && /^\d+$/.test(cells[0]))
    .map(([z, symbol, name, weight]) => {
      const match = weight.match(/^([\d.]+) ± ([\d.]+)$/);
      if (!match && weight !== "—") throw new Error(`${symbol}: unreadable weight "${weight}"`);
      return {
        number: Number(z),
        symbol,
        name: name[0].toUpperCase() + name.slice(1),
        weight: match ? { value: Number(match[1]), uncertainty: Number(match[2]) } : null,
      };
    });
  elements.forEach((element, i) => {
    if (element.number !== i + 1) throw new Error(`CIAAW row ${i + 1} is Z = ${element.number}`);
  });
  if (elements.length !== 118) throw new Error(`CIAAW lists ${elements.length} elements`);
  return elements;
}

const halfLife = (cell) => {
  const match = cell.match(/([\d.]+)(?:\([\d.]+\))?\s*(ms|s|min|h|d|a|ka|Ma)$/);
  if (!match) throw new Error(`unreadable half-life "${cell}"`);
  return Number(match[1]) * SECONDS[match[2]];
};

/** Z → mass number of the longest-lived isotope CIAAW lists. */
function parseRadioactive(html) {
  const longest = new Map();
  let current = null;
  for (const cells of rows(html)) {
    let isotope;
    if (cells.length === 5 && /^\d+$/.test(cells[0])) {
      current = Number(cells[0]);
      isotope = cells.slice(3);
    } else if (cells.length === 2 && current !== null) isotope = cells;
    else continue;
    const [mass, life] = [Number(isotope[0]), halfLife(isotope[1])];
    const best = longest.get(current);
    if (!best || life > best.life) longest.set(current, { mass, life });
  }
  return new Map([...longest].map(([z, { mass }]) => [z, mass]));
}

/** Z → NIST's symbol and standard atomic weight (a value, an interval, or a bracketed mass number). */
function parseNist(body) {
  const nist = new Map();
  const blocks = body
    .replace(/<[^>]*>/g, "")
    .split("Atomic Number = ")
    .slice(1);
  for (const block of blocks) {
    const z = Number.parseInt(block, 10);
    if (nist.has(z)) continue;
    const symbol = block.match(/Atomic Symbol = (\S+)/)?.[1];
    const weight = block.match(/Standard Atomic Weight = ([^\n]*)/)?.[1].trim() ?? "";
    nist.set(z, { symbol, weight });
  }
  return nist;
}

/** NIST's weight as a centre and a half-width, or null when it gives none. */
function nistRange(weight) {
  const interval = weight.match(/^\[([\d.]+),([\d.]+)\]$/);
  if (interval) {
    const [low, high] = [Number(interval[1]), Number(interval[2])];
    return { centre: (low + high) / 2, halfWidth: (high - low) / 2 };
  }
  const value = weight.match(/^([\d.]+)\((\d+)\)$/);
  if (!value) return null;
  const decimals = value[1].split(".")[1]?.length ?? 0;
  return { centre: Number(value[1]), halfWidth: Number(value[2]) / 10 ** decimals };
}

function verify(elements, nist) {
  for (const element of elements) {
    const entry = nist.get(element.number);
    if (entry?.symbol !== element.symbol)
      throw new Error(`Z = ${element.number}: CIAAW ${element.symbol}, NIST ${entry?.symbol}`);
    const range = nistRange(entry.weight);
    if (element.weight) {
      if (!range) throw new Error(`${element.symbol}: NIST gives no standard weight`);
      const gap = Math.abs(element.weight.value - range.centre);
      if (gap > element.weight.uncertainty + range.halfWidth + 1e-9)
        throw new Error(`${element.symbol}: CIAAW ${element.weight.value}, NIST ${entry.weight}`);
    } else if (range) throw new Error(`${element.symbol}: NIST gives a standard weight`);
    else if (entry.weight.startsWith("[") && entry.weight !== `[${element.massNumber}]`)
      console.warn(
        `${element.symbol}: NIST brackets ${entry.weight}, NUBASE2020 ${element.massNumber}`,
      );
  }
}

function generate(elements) {
  const unweighed = elements.filter((element) => !element.weight);
  const quote = (element) => `"${element.symbol}"`;
  return [
    BEGIN,
    "export const ELEMENT_SYMBOLS = [",
    ...elements.map((element) => `  ${quote(element)},`),
    "] as const;",
    "export type ElementSymbol = (typeof ELEMENT_SYMBOLS)[number];",
    "",
    "/** The elements without a standard atomic weight. */",
    "export type UnweighedSymbol =",
    ...unweighed.map(
      (element, i) => `  | ${quote(element)}${i === unweighed.length - 1 ? ";" : ""}`,
    ),
    "",
    "export const PERIODIC_TABLE: PeriodicTable = {",
    ...elements.map((element) => {
      const args = `${element.number}, ${quote(element)}, "${element.name}"`;
      return element.weight
        ? `  ${element.symbol}: weighed(${args}, ${element.weight.value}),`
        : `  ${element.symbol}: unweighed(${args}, ${element.massNumber}),`;
    }),
    "};",
    END,
  ].join("\n");
}

const [abridged, radioactive, nistBody, source] = await Promise.all([
  fetchText(ABRIDGED),
  fetchText(RADIOACTIVE),
  fetchText(NIST),
  readFile(OUT, "utf8"),
]);
const masses = parseRadioactive(radioactive);
const elements = parseAbridged(abridged).map((element) => {
  const massNumber = masses.get(element.number) ?? null;
  if ((massNumber === null) === (element.weight === null))
    throw new Error(`${element.symbol}: needs exactly one of a weight and a mass number`);
  return { ...element, massNumber };
});
if (masses.size !== elements.filter((element) => !element.weight).length)
  throw new Error("CIAAW's radioactive list does not match the elements without a weight");
verify(elements, parseNist(nistBody));

const start = source.indexOf(BEGIN);
const end = source.indexOf(END);
if (start < 0 || end < start) throw new Error(`${OUT.pathname}: generated markers not found`);
const next = source.slice(0, start) + generate(elements) + source.slice(end + END.length);

syncGenerated({ file: OUT, content: next, command: "node scripts/fetch-elements.mjs" });
