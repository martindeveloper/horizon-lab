import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => readFileSync(join(root, path), "utf8");
const lock = JSON.parse(read("package-lock.json"));
const fallbacks = {
  "@next/env": "node_modules/next/license.md",
  "babel-plugin-react-compiler": "node_modules/react/LICENSE",
  "client-only": "node_modules/react/LICENSE",
  // The npm tarball omits the upstream repository's licence.
  "@schummar/icu-type-parser": "scripts/licenses/icu-type-parser-LICENSE.txt",
};

function notices(directory, relative = "") {
  return readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, "en"))
    .flatMap((entry) => {
      const path = join(relative, entry.name);
      if (entry.isDirectory()) {
        return entry.name === "node_modules" ? [] : notices(join(directory, entry.name), path);
      }
      return entry.isFile() &&
        /^(licen[sc]e|copying|notice|copyright|ofl)([.-]|$)/i.test(entry.name)
        ? [path]
        : [];
    });
}

const sections = [];
for (const [path, meta] of Object.entries(lock.packages).sort(([a], [b]) =>
  a.localeCompare(b, "en"),
)) {
  if (!path.includes("node_modules/") || meta.dev || meta.link) continue;
  // Native build/server binaries and the SWC download counter are not browser assets.
  if (meta.os || meta.cpu || meta.optional || path.endsWith("/@swc/counter")) continue;
  if (!existsSync(join(root, path))) throw new Error(`Install dependencies first: ${path}`);
  const pkg = JSON.parse(read(`${path}/package.json`));
  const files = notices(join(root, path));
  const texts = files.map((file) => `--- ${file} ---\n${read(`${path}/${file}`)}`);
  if (!texts.length && fallbacks[pkg.name]) texts.push(read(fallbacks[pkg.name]));
  if (!texts.length)
    throw new Error(`Missing licence text for ${pkg.name}; review its upstream terms.`);
  sections.push(
    `${pkg.name}@${pkg.version}\n${path}\nDeclared licence: ${pkg.license ?? meta.license}\n\n${texts.join("\n\n")}`,
  );
}

const output = `Horizon — third-party software and font notices

Generated by npm run licenses:generate from installed, locked dependencies.
Includes platform-independent production dependencies and their bundled notices;
some entries run only on the server or during the build. Inclusion does not mean
that every listed component is sent to the browser. Native/optional build/server binaries
and the SWC download counter are outside this browser-distribution notice file.
Upstream licence texts below are reproduced without rewriting their terms.
Imagery and scientific data credits: /credits and /textures/orrery/CREDITS.md.
This file makes no statement about the provenance or rights of the ambient music.

${sections.join(`\n\n${"=".repeat(80)}\n\n`)}\n`;
const target = "public/THIRD-PARTY-NOTICES.txt";
if (process.argv.includes("--check")) {
  if (!existsSync(join(root, target)) || read(target) !== output) {
    throw new Error("Third-party notices are stale. Run npm run licenses:generate.");
  }
} else {
  writeFileSync(join(root, target), output);
}
