import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import test from "node:test";

import { glslDefines, glslFloat, glslHeader, glslInt } from "@horizon/toolkit/shaders/defines";

import { SHADER_HEADERS } from "../scripts/shader-headers.mjs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
const stripComments = (source) =>
  source.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\/\/[^\n]*/g, " ");

/** Each lab's shaders, with the header its parameters are generated into. */
function labShaders() {
  return SHADER_HEADERS.flatMap((header) => {
    const files =
      typeof header.shaders === "string"
        ? readdirSync(new URL(header.shaders, root))
            .filter((file) => /\.(vert|frag)\.glsl$/.test(file))
            .map((file) => `${header.shaders}${file}`)
        : header.shaders;
    return files.map((path) => ({ path, header, code: stripComments(read(path)) }));
  });
}

/** Significant digits a literal states: "0.4213" → 4, "48.0" → 2, "15800.0" → 5. */
function significantDigits(literal) {
  const [mantissa] = literal.toLowerCase().split("e");
  const digits = mantissa.includes(".")
    ? mantissa.replace(".", "").replace(/^0+/, "").replace(/0+$/, "")
    : mantissa.replace(/^0+/, "");
  return digits.length;
}
const decimals = (literal) => {
  const [mantissa, exponent = "0"] = literal.toLowerCase().split("e");
  return (mantissa.split(".")[1]?.length ?? 0) - Number(exponent);
};

test("GLSL literals are valid floats, ints and vectors", () => {
  assert.equal(glslFloat(15800), "15800.0");
  assert.equal(glslFloat(1.68), "1.68");
  assert.equal(glslFloat(2 * Math.PI), "6.283185307");
  assert.equal(glslFloat(1e-7), "1.0e-7");
  assert.equal(glslFloat(-0.5), "-0.5");
  assert.deepEqual(glslDefines({ STEPS: glslInt(180), TINT: [1, 0.5, 0] }), {
    STEPS: "180",
    TINT: "vec3(1.0, 0.5, 0.0)",
  });
  assert.throws(() => glslFloat(Number.NaN), RangeError);
  assert.throws(() => glslInt(1.5), RangeError);
  assert.throws(() => glslDefines({ lowercase: 1 }), TypeError);
  assert.throws(() => glslDefines({ V: [1] }), RangeError);
  assert.equal(
    glslHeader({ A: "1.0", LONG_NAME: "2" }, { guard: "G", source: "x.ts", command: "gen" }),
    "// Generated by `gen` from x.ts. Do not edit.\n#ifndef G\n#define G\n\n#define A         1.0\n#define LONG_NAME 2\n\n#endif // G\n",
  );
});

test("generated shader headers match their TypeScript parameters", () => {
  for (const { path, contents } of SHADER_HEADERS)
    assert.equal(read(path), contents, `${path} is stale: run npm run shaders:generate`);
});

test("lab shaders declare no numeric constants: their numbers come from the header", () => {
  for (const { path, code } of labShaders()) {
    const typed = code.match(/^\s*const\s+(?:float|int|vec[234])\s+\w+\s*=\s*[-\d.(v]/m);
    assert.equal(typed, null, `${path}: ${typed?.[0].trim()}; move it to the lab's parameters`);
  }
});

test("shaders include their lab header to use it, and every parameter is used", () => {
  for (const header of SHADER_HEADERS) {
    const shaders = labShaders().filter((shader) => shader.header === header);
    const names = Object.keys(header.defines);
    for (const { path, code } of shaders) {
      const uses = names.filter((name) => new RegExp(`\\b${name}\\b`).test(code));
      const includes = /#\s*include\s+"\.\/(?:\.\.\/)*[\w./-]*parameters\.generated\.glsl"/.test(
        code,
      );
      assert.equal(
        includes,
        uses.length > 0,
        `${path}: include the header exactly when it is used`,
      );
    }
    for (const name of names)
      assert.ok(
        shaders.some(({ code }) => new RegExp(`\\b${name}\\b`).test(code)),
        `${header.lab}: ${name} is generated but no shader uses it`,
      );
  }
});

test("no lab shader re-types a number its header provides", () => {
  for (const { path, header, code } of labShaders()) {
    const values = Object.entries(header.defines)
      .filter(([, literal]) => /^-?[\d.]/.test(literal) && significantDigits(literal) >= 3)
      .map(([name, literal]) => [name, Number(literal)]);
    for (const [literal] of code.matchAll(/(?<![\w.])\d+\.?\d*(?:e[-+]?\d+)?/gi)) {
      if (significantDigits(literal) < 3) continue;
      const tolerance = 0.5 * 10 ** -decimals(literal);
      for (const [name, value] of values)
        assert.ok(
          Math.abs(Number(literal) - value) > tolerance,
          `${path}: ${literal} re-types ${name}; use the define`,
        );
    }
    assert.doesNotMatch(code, /6\.28318|3\.14159/, `${path}: use PI / TWO_PI from <horizon/math>`);
  }
});

test("shader parameters keep their physics", () => {
  const [blackHole, orrery] = SHADER_HEADERS.map((header) => header.defines);
  // Limb darkening is flux-normalised: ∫₀¹ 2μ N (1 + c μ) dμ = 1.
  const c = Number(blackHole.LIMB_DARKENING);
  const n = Number(blackHole.LIMB_NORMALIZATION);
  assert.ok(Math.abs(n * (1 + (2 / 3) * c) - 1) < 1e-9);
  assert.equal(Number(blackHole.DISK_PROFILE_LAST), Number(blackHole.DISK_PROFILE_SIZE) - 1);
  assert.ok(Math.abs(Number(orrery.SWARM_TROJAN_OFFSET) - Math.PI / 3) < 1e-9);
});
