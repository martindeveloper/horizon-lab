/**
 * The periodic table from hydrogen to oganesson (Z = 1–118). Each element has its atomic number,
 * symbol, English name (for code and documents; hosts translate what they show), its standard
 * atomic weight or, without one, the mass number of its longest-lived isotope, and its place in
 * the table.
 *
 * The data are generated from IUPAC's Commission on Isotopic Abundances and Atomic Weights by
 * scripts/fetch-elements.mjs and cross-checked against NIST; see the science README.
 */

/** The block an element sits in: which subshell its outermost electrons fill. */
export type PeriodicBlock = "s" | "p" | "d" | "f";

type ElementFacts = {
  /** Atomic number Z: protons in the nucleus. */
  number: number;
  symbol: ElementSymbol;
  /** English name (IUPAC spelling). */
  name: string;
  /** Row of the table, 1–7. */
  period: number;
  /**
   * Column of the table, 1–18 (IUPAC numbering); null in the f block, whose fourteen columns
   * have no group number. Group 3 is Sc, Y, Lu and Lr.
   */
  group: number | null;
  block: PeriodicBlock;
};

/**
 * An element with a standard atomic weight: every stable element, and thorium, protactinium and
 * uranium, whose long-lived isotopes give them a characteristic composition on Earth.
 */
export type ChemicalElement = ElementFacts & {
  /** Abridged standard atomic weight, u (IUPAC CIAAW, five significant figures). */
  atomicWeight: number;
  massNumber: null;
};

/**
 * An element with no stable isotopes and no characteristic terrestrial composition, so no
 * standard atomic weight (Tc, Pm, Po–Ac and Np onwards).
 */
export type UnweighedElement = ElementFacts & {
  atomicWeight: null;
  /** Mass number of its longest-lived known isotope: the bracketed number of printed tables. */
  massNumber: number;
};

/** Any element; `atomicWeight !== null` narrows it to a `ChemicalElement`. */
export type PeriodicElement = ChemicalElement | UnweighedElement;

export type PeriodicTable = {
  readonly [S in ElementSymbol]: S extends UnweighedSymbol ? UnweighedElement : ChemicalElement;
};

/** The noble gases close each period, so Z alone fixes the row. */
const PERIOD_ENDS = [2, 10, 18, 36, 54, 86, 118];

/** Period, group and block from Z, with the f block (La–Yb, Ac–No) between groups 2 and 3. */
function place(number: number): Pick<ElementFacts, "period" | "group" | "block"> {
  const period = PERIOD_ENDS.findIndex((end) => number <= end) + 1;
  /* Position in the row, from 1. */
  const column = number - (PERIOD_ENDS[period - 2] ?? 0);
  /* Helium sits over the p block but fills an s shell. */
  if (period === 1) return { period, group: column === 1 ? 1 : 18, block: "s" };
  if (column <= 2) return { period, group: column, block: "s" };
  if (period <= 3) return { period, group: column + 10, block: "p" };
  if (period >= 6 && column <= 16) return { period, group: null, block: "f" };
  const group = period >= 6 ? column - 14 : column;
  return { period, group, block: group <= 12 ? "d" : "p" };
}

function weighed(
  number: number,
  symbol: Exclude<ElementSymbol, UnweighedSymbol>,
  name: string,
  atomicWeight: number,
): ChemicalElement {
  return { number, symbol, name, atomicWeight, massNumber: null, ...place(number) };
}

function unweighed(
  number: number,
  symbol: UnweighedSymbol,
  name: string,
  massNumber: number,
): UnweighedElement {
  return { number, symbol, name, atomicWeight: null, massNumber, ...place(number) };
}

/** Whether a string names an element in the table. */
export const isElementSymbol = (symbol: string): symbol is ElementSymbol =>
  (ELEMENT_SYMBOLS as readonly string[]).includes(symbol);

