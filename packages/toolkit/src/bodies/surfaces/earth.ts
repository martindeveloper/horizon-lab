/** Mean cloud cover by latitude (ISCCP climatology, roughly): wet tropics and storm tracks. */
function cloudiness(lat: number) {
  const itcz = Math.exp(-(((lat - 6) / 8) ** 2)) * 0.32;
  const storms = Math.exp(-(((Math.abs(lat) - 55) / 12) ** 2)) * 0.38;
  return 0.42 + itcz + storms - Math.exp(-(((Math.abs(lat) - 24) / 9) ** 2)) * 0.18;
}

export function earth(w: number, h: number): Painter {
  const land = coverage(LAND, w, h);
  const seas = coverage(SEAS, w, h);
  /* Deserts fade over a few degrees: a coarse coverage grid, sampled bilinearly. */
  const dry = soft(coverage(DRY, 90, 45), 90, 45);
  const ice = coverage(ICE_SHEETS, w, h);
  return (p) => {
    const { lon, lat } = p;
    /* Crinkle the simplified coastlines by about a degree; large maps add finer wiggles. */
    const wLon = (fbm(p, 22, 22, 2, 20) - 0.5) * 2.4;
    const wLat = (fbm(p, 22, 22, 2, 21) - 0.5) * 1.8;
    const x = Math.floor((((lon + wLon + 360) % 360) / 360) * w) % w;
    const y = Math.min(h - 1, Math.max(0, Math.floor(((90 - lat - wLat) / 180) * h)));
    const i = y * w + x;
    const n = fbm(p, 9, 9, 3, 1);
    const a = Math.abs(lat);
    let ground = mix(FOREST, SAVANNA, smooth(9, 16, a));
    ground = mix(ground, TEMPERATE, smooth(28, 36, a));
    ground = mix(ground, BOREAL, smooth(50, 58, a));
    ground = mix(ground, TUNDRA, smooth(64, 70, a));
    ground = mix(ground, DESERT, smooth(0.3, 0.7, dry(lon + wLon, lat + wLat) + (n - 0.5) * 0.5));
    ground = mix(ground, scale(ground, 1.25), n - 0.4);
    ground = mix(ground, ICE, ice[i]!);
    let water = mix(OCEAN_DEEP, OCEAN_SHELF, smooth(0.45, 0.75, n));
    /* Sea ice: the Arctic pack and the Antarctic pack near its October maximum. */
    water = mix(water, ICE, smooth(76, 82, lat) + smooth(-62, -68, lat));
    let rgb = mix(water, ground, clamp01(land[i]! - seas[i]!));
    /* Cloud fields: patchy everywhere, thicker in the wet tropics and storm tracks. */
    /* Warped by the ground noise so the fields swirl rather than tile. */
    const warp = (n - 0.5) * 0.6;
    const c = fbmAt(p.x + warp, p.y - warp * 0.5, p.z - warp, 5, 8, 4, 2);
    const t = 0.44 - (cloudiness(lat) - 0.5) * 0.4;
    rgb = mix(rgb, CLOUD, smooth(t - 0.06, t + 0.22, c) * 0.9);
    return rgb;
  };
}

/** Fraction of the surface (area-weighted) that the Earth map paints as land, for tests. */
export function earthLandFraction(w: number, h: number) {
  const land = coverage(LAND, w, h);
  const seas = coverage(SEAS, w, h);
  let sum = 0;
  let total = 0;
  for (let y = 0; y < h; y += 1) {
    const weight = Math.cos((90 - ((y + 0.5) / h) * 180) * RAD);
    for (let x = 0; x < w; x += 1) {
      sum += clamp01(land[y * w + x]! - seas[y * w + x]!) * weight;
      total += weight;
    }
  }
  return sum / total;
}
