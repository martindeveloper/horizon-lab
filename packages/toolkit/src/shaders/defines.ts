/**
 * Shader parameters from TypeScript. The numbers live once in the science
 * library or a feature's parameters, where tests check them; `glslHeader`
 * writes them into a committed `.glsl` header that shaders `#include`, so the
 * shader source is complete for editors, linters and offline compilers. The
 * same `glslDefines` output also works as `ShaderMaterial.defines` for values
 * chosen at material creation. Defines are compile-time: anything that changes
 * while the scene runs stays a uniform.
 */

/** A float, an integer (`glslInt`), or a vec2–vec4 of floats. */
export type GlslValue = number | GlslInt | readonly number[];
export type GlslInt = { readonly int: number };
export type GlslDefines = Record<string, string>;

const NAME = /^[A-Z][A-Z0-9_]*$/;

/** Marks a value as a GLSL `int` (loop bounds, counts). */
export const glslInt = (value: number): GlslInt => {
  if (!Number.isInteger(value)) throw new RangeError(`GLSL int must be an integer: ${value}`);
  return { int: value };
};

/**
 * A float literal GLSL ES 3.0 accepts: always a decimal point or exponent,
 * 10 significant digits (float32 keeps about 7), no locale.
 */
export function glslFloat(value: number) {
  if (!Number.isFinite(value)) throw new RangeError(`GLSL float must be finite: ${value}`);
  const text = Number(value.toPrecision(10)).toString();
  if (/e/i.test(text)) {
    const [mantissa, exponent] = text.split(/e/i);
    if (mantissa === undefined || exponent === undefined) return text;
    return `${mantissa.includes(".") ? mantissa : `${mantissa}.0`}e${exponent.replace("+", "")}`;
  }
  return text.includes(".") ? text : `${text}.0`;
}

function literal(name: string, value: GlslValue) {
  if (typeof value === "number") return glslFloat(value);
  if ("int" in value) return String(value.int);
  if (value.length < 2 || value.length > 4)
    throw new RangeError(`${name}: vectors have 2–4 components`);
  return `vec${value.length}(${value.map(glslFloat).join(", ")})`;
}

/** Turns named values into GLSL define values: `{ DISK_PEAK_K: "15800.0" }`. */
export function glslDefines(values: Record<string, GlslValue>): GlslDefines {
  const defines: GlslDefines = {};
  for (const [name, value] of Object.entries(values)) {
    if (!NAME.test(name)) throw new TypeError(`Shader define names are UPPER_SNAKE_CASE: ${name}`);
    defines[name] = literal(name, value);
  }
  return defines;
}

export type GlslHeaderOptions = {
  /** Include guard, e.g. `HORIZON_BLACK_HOLE_PARAMETERS`. */
  guard: string;
  /** Where the values come from, for the "do not edit" banner. */
  source: string;
  /** The command that regenerates the file. */
  command: string;
};

/**
 * A committed GLSL header holding the defines, so shaders `#include` real
 * definitions: editors, linters and offline compilers see every name, and the
 * numbers still live once in TypeScript. Regenerate with the given command and
 * check freshness in CI by comparing the file with this output.
 */
export function glslHeader(defines: GlslDefines, { guard, source, command }: GlslHeaderOptions) {
  if (!NAME.test(guard)) throw new TypeError(`Header guards are UPPER_SNAKE_CASE: ${guard}`);
  const width = Math.max(0, ...Object.keys(defines).map((name) => name.length));
  return [
    `// Generated by \`${command}\` from ${source}. Do not edit.`,
    `#ifndef ${guard}`,
    `#define ${guard}`,
    "",
    ...Object.entries(defines).map(([name, value]) => `#define ${name.padEnd(width)} ${value}`),
    "",
    `#endif // ${guard}`,
    "",
  ].join("\n");
}
